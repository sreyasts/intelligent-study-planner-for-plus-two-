export function normalizeHandbookGrade(grade) {
  if (!grade && grade !== 0) return null;
  const s = String(grade).trim().toLowerCase().replace(/[^a-z0-9]/g, '');
  if (s === '1' || s === '11' || s === 'plusone' || s === 'plus1' || s === 'plus_one' || s === 'one') return '+1';
  if (s === '2' || s === '12' || s === 'plustwo' || s === 'plus2' || s === 'plus_two' || s === 'two') return '+2';
  return null;
}

export function normalizeHandbookSubject(subject) {
  if (!subject) return null;
  const s = String(subject).trim();
  const lower = s.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (lower === 'physics' || lower === 'phy') return 'Physics';
  if (lower === 'chemistry' || lower === 'chem') return 'Chemistry';
  if (lower === 'mathematics' || lower === 'maths' || lower === 'math') return 'Mathematics';
  if (lower === 'botany' || lower === 'bot') return 'Botany';
  if (lower === 'zoology' || lower === 'zoo') return 'Zoology';
  if (lower.startsWith('biology') || lower === 'bio') {
    if (lower.includes('botany') || lower.includes('bot')) return 'Botany';
    if (lower.includes('zoology') || lower.includes('zoo')) return 'Zoology';
    return 'Botany';
  }
  if (lower === 'computerscience' || lower === 'cs') return 'Computer_Science';
  if (lower === 'accountancy' || lower === 'acc') return 'Accountancy';
  if (lower === 'businessstudies' || lower === 'bst' || lower === 'business') return 'Business_Studies';
  if (lower === 'economics' || lower === 'econ') return 'Economics';
  if (lower === 'computerapplications' || lower === 'ca') return 'Computer_Applications';
  if (lower === 'history' || lower === 'hist') return 'History';
  if (lower === 'politicalscience' || lower === 'pol' || lower === 'polsci') return 'Political_Science';
  if (lower === 'sociology' || lower === 'soc') return 'Sociology';
  if (lower === 'statistics' || lower === 'stat' || lower === 'stats') return 'Statistics';
  if (lower === 'geography' || lower === 'geo') return 'Geography';
  return s.replace(/\s+/g, '_');
}

export function normalizeHandbookTitle(title) {
  return String(title || '').toLowerCase().replace(/[^a-z0-9]/g, '');
}

function resolveStreamPath(relPath, stream) {
  if (!relPath || !stream) return relPath;
  const s = String(stream).toLowerCase();
  let targetStream = null;
  if (s.includes('bio')) targetStream = 'Biology_Science';
  else if (s.includes('cs') || (s.includes('comp') && !s.includes('app'))) targetStream = 'Computer_Science';
  else if (s.includes('comm')) targetStream = 'Commerce';
  else if (s.includes('hum')) targetStream = 'Humanities';
  if (!targetStream) return relPath;

  if (targetStream === 'Biology_Science') {
    if (relPath.includes('/Computer_Science/Physics/')) return relPath.replace('/Computer_Science/Physics/', '/Biology_Science/Physics/');
    if (relPath.includes('/Computer_Science/Chemistry/')) return relPath.replace('/Computer_Science/Chemistry/', '/Biology_Science/Chemistry/');
    if (relPath.includes('/Computer_Science/Maths/')) return relPath.replace('/Computer_Science/Maths/', '/Biology_Science/Maths/');
  } else if (targetStream === 'Computer_Science') {
    if (relPath.includes('/Biology_Science/Physics/')) return relPath.replace('/Biology_Science/Physics/', '/Computer_Science/Physics/');
    if (relPath.includes('/Biology_Science/Chemistry/')) return relPath.replace('/Biology_Science/Chemistry/', '/Computer_Science/Chemistry/');
    if (relPath.includes('/Biology_Science/Maths/')) return relPath.replace('/Biology_Science/Maths/', '/Computer_Science/Maths/');
  } else if (targetStream === 'Commerce') {
    if (relPath.includes('/Computer_Science/Maths/') || relPath.includes('/Biology_Science/Maths/')) {
      return relPath.replace(/\/(?:Computer_Science|Biology_Science)\/Maths\//, '/Commerce/Maths/');
    }
    if (relPath.includes('/Humanities/Economics/')) return relPath.replace('/Humanities/Economics/', '/Commerce/Economics/');
  } else if (targetStream === 'Humanities') {
    if (relPath.includes('/Commerce/Economics/')) return relPath.replace('/Commerce/Economics/', '/Humanities/Economics/');
  }
  return relPath;
}

/**
 * Get verified handbook URL for a task, chapter, or query options
 * @param {object | string} taskOrOptions Task object, options object, or chapId string
 * @param {object} [contextState] Optional state context (e.g. appState or { stream })
 * @returns {string | null} Web-safe URL (e.g. '/handbooks/+1/...') or null if unavailable / rationalized
 */
export function getHandbookUrl(taskOrOptions, contextState = {}) {
  if (!taskOrOptions) return null;

  const opts = typeof taskOrOptions === 'string' ? { chapId: taskOrOptions } : taskOrOptions;
  const effectiveStream = opts.stream || contextState.stream || contextState.activeStream || null;

  // Extract direct chapId if provided
  let rawChapId = opts.chapId || null;
  if (!rawChapId && typeof opts.id === 'string' && /^[+]\d_/.test(opts.id)) {
    rawChapId = opts.id.replace(/_P\d+$/, '');
  }

  // Tier 1: Direct lookup by canonical chapId
  if (rawChapId) {
    if (RATIONALIZED_CHAPTER_IDS.has(rawChapId)) return null;
    if (Object.hasOwn(CANONICAL_HANDBOOK_MAP, rawChapId)) {
      const mapped = CANONICAL_HANDBOOK_MAP[rawChapId];
      if (mapped === null) return null;
      return '/handbooks/' + resolveStreamPath(mapped, effectiveStream);
    }
    const normalizedRawId = rawChapId.replace(/\s+/g, '_');
    if (Object.hasOwn(CANONICAL_HANDBOOK_MAP, normalizedRawId)) {
      const mapped = CANONICAL_HANDBOOK_MAP[normalizedRawId];
      if (mapped === null) return null;
      return '/handbooks/' + resolveStreamPath(mapped, effectiveStream);
    }
  }

  // Tier 2: Synthetic chapId lookup
  const grade = normalizeHandbookGrade(opts.grade || opts.level || contextState.grade || contextState.academicLevel);
  const subject = normalizeHandbookSubject(opts.subject || opts.sub_subject || opts.subjectName);
  const chapNumber = opts.chapNumber !== undefined ? opts.chapNumber : (opts.num !== undefined ? opts.num : opts.chapter_number);

  if (grade && subject && chapNumber !== undefined && chapNumber !== null) {
    const synthId = grade + '_' + subject + '_' + parseInt(chapNumber, 10);
    if (RATIONALIZED_CHAPTER_IDS.has(synthId)) return null;
    if (Object.hasOwn(CANONICAL_HANDBOOK_MAP, synthId)) {
      const mapped = CANONICAL_HANDBOOK_MAP[synthId];
      if (mapped === null) return null;
      return '/handbooks/' + resolveStreamPath(mapped, effectiveStream);
    }
  }

  // Tier 3: Normalized title match
  const rawTitle = opts.chapterName || opts.chapter_title || opts.title || opts.name || null;
  if (grade && rawTitle) {
    const normTitle = normalizeHandbookTitle(rawTitle);
    if (subject) {
      const subKey = grade + '|' + normalizeHandbookTitle(subject) + '|' + normTitle;
      if (Object.hasOwn(TITLE_HANDBOOK_MAP, subKey)) {
        const mapped = TITLE_HANDBOOK_MAP[subKey];
        if (mapped === null) return null;
        return '/handbooks/' + resolveStreamPath(mapped, effectiveStream);
      }
    }
    const titleKey = grade + '|' + normTitle;
    if (Object.hasOwn(TITLE_HANDBOOK_MAP, titleKey)) {
      const mapped = TITLE_HANDBOOK_MAP[titleKey];
      if (mapped === null) return null;
      return '/handbooks/' + resolveStreamPath(mapped, effectiveStream);
    }
  }

  return null;
}

/**
 * Check if a verified handbook exists for a task or chapter
 * @param {object | string} taskOrOptions
 * @returns {boolean}
 */
export function hasHandbook(taskOrOptions) {
  return getHandbookUrl(taskOrOptions) !== null;
}

/**
 * Get full metadata and URL for a chapter handbook
 * @param {object | string} taskOrOptions
 * @param {object} [contextState]
 * @returns {object | null}
 */
export function getHandbookInfo(taskOrOptions, contextState = {}) {
  const url = getHandbookUrl(taskOrOptions, contextState);
  if (!url) {
    const rawChapId = typeof taskOrOptions === 'string' ? taskOrOptions : (taskOrOptions?.chapId || null);
    const isRat = rawChapId ? RATIONALIZED_CHAPTER_IDS.has(rawChapId) : false;
    return {
      url: null,
      relativePath: null,
      filename: null,
      available: false,
      rationalized: isRat,
    };
  }
  const relativePath = url.replace(/^\/handbooks\//, '');
  const filename = relativePath.split('/').pop();
  return {
    url,
    relativePath,
    filename,
    available: true,
    rationalized: false,
  };
}
